from __future__ import annotations

from dataclasses import replace
from pathlib import Path

import pytest

from credit_risk.config import load_config
from credit_risk.tuning import search

pytest.importorskip("optuna")


@pytest.fixture
def fast_config(project):
    return replace(
        project.cfg,
        train=replace(
            project.cfg.train,
            candidates=["logistic"],
            search=replace(project.cfg.train.search, trials=2, timeout_seconds=0),
        ),
    )


@pytest.mark.modern
def test_tune_returns_best_params_and_writes_config(fast_config, tmp_path: Path) -> None:
    results = search.tune(fast_config, models=["logistic"], trials=2, timeout=0)
    entry = results["models"]["logistic"]
    assert entry["trials"] >= 1
    assert entry["best_value"] > 0
    assert "C" in entry["best_params"]

    destination = tmp_path / "tuned.yaml"
    source = Path(fast_config.source_file)
    written = search.write_tuned_config(fast_config, results, source, destination)
    text = written.read_text(encoding="utf-8")
    assert "# Generated by" in text
    assert "# logistic: best" in text

    reloaded = load_config(written, root=fast_config.root)
    assert reloaded.train.logistic["C"] == entry["best_params"]["C"]
    assert reloaded.train.candidates == ["logistic"]


@pytest.mark.modern
def test_search_space_is_bounded(fast_config) -> None:
    optuna = pytest.importorskip("optuna")
    for model_type in ("logistic", "lightgbm", "xgboost", "catboost"):
        study = optuna.create_study()
        trial = study.ask()
        params = search.suggest(trial, model_type)
        assert params, model_type


@pytest.mark.modern
def test_unavailable_optuna_is_reported(fast_config, monkeypatch) -> None:
    monkeypatch.setattr(search, "available", lambda: False)
    with pytest.raises(search.OptunaUnavailable, match="optuna"):
        search.tune(fast_config, models=["logistic"], trials=1)
